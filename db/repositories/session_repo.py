"""Session repository. Backed by the sessions table."""

from __future__ import annotations

import sqlite3
from datetime import timedelta

from db.repositories.base import BaseRepository


class SessionRepository(BaseRepository):
    """Reads and writes session rows.

    The session id is an opaque token generated by the caller. The repo
    never sees raw passwords, only the session id, csrf token, and metadata.
    """

    def create(
        self,
        session_id: str,
        user_id: int,
        ttl_seconds: int,
        csrf_token: str,
        ip: str | None = None,
        user_agent: str | None = None,
    ) -> None:
        expires_at = self.iso(self.utcnow() + timedelta(seconds=ttl_seconds))

        def work(conn: sqlite3.Connection) -> None:
            conn.execute(
                """
                INSERT INTO sessions
                    (id, user_id, expires_at, csrf_token, ip, user_agent, revoked)
                VALUES (?, ?, ?, ?, ?, ?, 0);
                """,
                (session_id, user_id, expires_at, csrf_token, ip, user_agent),
            )

        self.write(work)

    def by_id(self, session_id: str) -> dict | None:
        def work(conn: sqlite3.Connection):
            return conn.execute(
                "SELECT * FROM sessions WHERE id = ?;", (session_id,)
            ).fetchone()

        row = self.read(work)
        return self.row_to_dict(row)

    def touch(self, session_id: str, ttl_seconds: int) -> None:
        expires_at = self.iso(self.utcnow() + timedelta(seconds=ttl_seconds))

        def work(conn: sqlite3.Connection) -> None:
            conn.execute(
                "UPDATE sessions SET expires_at = ? WHERE id = ?;",
                (expires_at, session_id),
            )

        self.write(work)

    def revoke(self, session_id: str) -> None:
        def work(conn: sqlite3.Connection) -> None:
            conn.execute(
                "UPDATE sessions SET revoked = 1 WHERE id = ?;", (session_id,)
            )

        self.write(work)

    def revoke_all_for_user(self, user_id: int) -> None:
        def work(conn: sqlite3.Connection) -> None:
            conn.execute(
                "UPDATE sessions SET revoked = 1 WHERE user_id = ?;", (user_id,)
            )

        self.write(work)

    def delete(self, session_id: str) -> None:
        def work(conn: sqlite3.Connection) -> None:
            conn.execute("DELETE FROM sessions WHERE id = ?;", (session_id,))

        self.write(work)

    def cleanup_expired(self) -> int:
        now = self.iso(self.utcnow())

        def work(conn: sqlite3.Connection) -> int:
            cur = conn.execute(
                "DELETE FROM sessions WHERE expires_at < ? OR revoked = 1;",
                (now,),
            )
            return int(cur.rowcount or 0)

        return self.write(work)